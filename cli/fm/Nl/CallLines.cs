	/// <summary>The line for a call, in the CLI's language; null for a tool with none.</summary>
	public static string? Of(string tool, JsonObject args, Func<string, string, string> choice)
	{
		foreach (var (key, line) in Lines)
		{
			var parts = key.Split(' ');
			if (parts[0] != tool || !parts.Skip(1).All(p => Holds(args, p))) continue;
			return Fill(Raw(line), a => Mcp.ArgumentSchema(tool, a)?["enum"] is JsonArray { Count: > 0 } ? choice(a, Shown(args[a])) : Shown(args[a]));
		}
		return null;
	}

	/// <summary>Every line as written, with its key: for the test that each one is translated with the same holes.</summary>
	public static IEnumerable<(string Key, string Line)> All => Lines;

	// "arg=value": the argument holds that choice; "arg": it is given (a text, a list, a number, or true)
	private static bool Holds(JsonObject args, string condition) =>
		condition.Split('=', 2) is [var name, var value] ? Shown(args[name]) == value : Shown(args[condition]).Length > 0;

	private static string Shown(JsonNode? node) => node switch
	{
		null => "",
		JsonArray list => string.Join(", ", list.Select(Shown).Where(s => s.Length > 0)),
		JsonValue v when v.TryGetValue<string>(out var s) => s.Trim(),
		JsonValue v when v.TryGetValue<bool>(out var b) => b ? "true" : "",
		_ => node.ToString(),
	};

	private static string Fill(string line, Func<string, string> value) =>
		System.Text.RegularExpressions.Regex.Replace(line, @"\{([a-z_]+)\}", m => value(m.Groups[1].Value));

	/// <summary>A line in the CLI's language with its {holes} left as they are.</summary>
	private static string Raw(string line) => Labels.Named(line);
}
